// Generates the TypeScript a client queries with from a server's introspection: per model, the
// interface a query reads it through and the row a query projecting nothing comes back as; the enums
// those name; the sources and commands; and a description of all of it for what the types cannot say
// at run time. The same reading of the description the explorer's ModelSynthesizer makes, so a query
// written against either sends the same request.

import { ScryIntrospection } from "../wire.ts";
import type { ScryCommandInfo, ScryEnumInfo, ScryMemberInfo, ScrySourceInfo, ScryTypeInfo } from "../wire.ts";
import { camelCase } from "../runtime/naming.ts";
import type {
  CommandInfo,
  EnumInfo,
  MemberInfo,
  ModelInfo,
  Scalar,
  ScrySchema,
  ShapeInfo,
  SourceInfo,
  ValueInfo
} from "../runtime/schema.ts";
import { parseDisplay } from "./display.ts";
import type { Display, Known } from "./display.ts";
import bclEnums from "../../../../src/Scry.Tests/TypeScript/bcl-enums.verified.json" with { type: "json" };

export interface GenerateOptions {
  /** The module the generated code imports the runtime's types from. */
  readonly runtime: string;
  /** Where the description came from, written into the header. */
  readonly from: string;
}

const modelSuffix = "QueryModel";

const scalarTypes: Readonly<Record<Scalar, string>> = {
  bool: "boolean",
  char: "string",
  sbyte: "number",
  byte: "number",
  short: "number",
  ushort: "number",
  int: "number",
  uint: "number",
  float: "number",
  double: "number",
  // Past what a number holds exactly, so read as text or as a bigint.
  long: "bigint",
  ulong: "bigint",
  decimal: "scry.Decimal",
  string: "string",
  bytes: "Uint8Array",
  DateTime: "scry.DateTime",
  DateOnly: "scry.DateOnly",
  TimeOnly: "scry.TimeOnly",
  DateTimeOffset: "scry.DateTimeOffset",
  TimeSpan: "scry.TimeSpan",
  Guid: "scry.Guid"
};

interface DescribedEnum {
  readonly name: string;
  readonly info: EnumInfo;
}

export function generate(description: ScryIntrospection, options: GenerateOptions): string {
  if (description.version !== ScryIntrospection.CurrentVersion) {
    throw new Error(`The description is introspection version ${description.version}, and this generator reads version ${ScryIntrospection.CurrentVersion}.`);
  }

  return new Generator(description).write(options);
}

class Generator {
  readonly #description: ScryIntrospection;
  readonly #types: ReadonlyMap<string, ScryTypeInfo>;
  readonly #enums = new Map<string, DescribedEnum>();
  readonly #used = new Set<string>();
  readonly #identifiers = new Map<string, string>();
  readonly #known: Known;

  constructor(description: ScryIntrospection) {
    this.#description = description;
    this.#types = new Map(description.types.map(_ => [_.model, _]));

    // A model's enum is described by the server. One of the base class library's is named by its
    // display alone, since a C# client already has it, so its values come from the table the server
    // holds itself to.
    for (const described of description.enums) {
      this.#enums.set(described.name, { name: described.name, info: enumInfo(described) });
    }

    for (const bcl of bclEnums) {
      this.#enums.set(bcl.display, { name: bcl.name, info: { ...enumInfo(bcl), system: bcl.display.slice("global::".length) } });
    }

    this.#known = {
      enums: new Map([...this.#enums].map(([display, described]) => [display, described.name])),
      models: new Set(this.#types.keys())
    };
  }

  write(options: GenerateOptions): string {
    const models = this.#writeModels();
    const sources = this.#writeSources();
    const commands = this.#writeCommands();
    // Written after everything that names an enum, since only then is it known which are named, and
    // placed first in the file.
    const enums = this.#writeEnums();
    const schema = this.#writeSchema();
    return [this.#header(options), enums, models, sources, commands, schema].join("\n");
  }

  #header(options: GenerateOptions): string {
    return [
      "// Generated by scry-codegen. Do not edit: generate it again when the server's model changes.",
      `// From: ${options.from}`,
      `// Schema stamp: ${this.#description.schemaStamp}`,
      "",
      `import type * as scry from ${JSON.stringify(options.runtime)};`,
      ""
    ].join("\n");
  }

  #writeEnums(): string {
    const lines: string[] = [];
    const named = [...this.#used].sort(ordinal);
    for (const name of named) {
      const described = this.#enumNamed(name);
      this.#declare(name, `the enum '${name}'`);
      lines.push(`export const ${name} = [`);
      for (const value of described.info.values) {
        lines.push(`  ${JSON.stringify(value)},`);
      }

      lines.push("] as const;");
      lines.push(`export type ${name} = (typeof ${name})[number];`);
      lines.push("");
    }

    return lines.join("\n");
  }

  #writeModels(): string {
    const lines: string[] = [];
    for (const type of this.#description.types) {
      const stem = stemOf(type.model);
      this.#declare(`${stem}Query`, `the query model for '${type.model}'`);
      this.#declare(`${stem}Row`, `the row for '${type.model}'`);
      this.#checkNames(type);

      const extending = this.#extending(type);
      lines.push(...docs(`${stem}, as a query reads it.`, type.obsolete));
      lines.push(`export interface ${stem}Query${extending("Query")} {`);
      for (const member of declaredOrder(type, type.members)) {
        const display = this.#display(type, member);
        const spelling = this.#querySpelling(display);
        if (spelling === undefined) {
          continue;
        }

        lines.push(...docs(undefined, member.obsolete).map(_ => `  ${_}`));
        lines.push(`  readonly ${camelCase(member.name)}: ${spelling};`);
      }

      lines.push("}");
      lines.push("");

      lines.push(...docs(`${stem}, as a row comes back from a query that projects nothing.`, type.obsolete));
      lines.push(`export interface ${stem}Row${extending("Row")} {`);
      for (const member of declaredOrder(type, type.members.filter(isScalar))) {
        const display = this.#display(type, member);
        if (display.kind !== "value") {
          throw new Error(`'${type.model}.${member.name}' is a scalar to introspection but its display, '${member.typeDisplay}', is not a value.`);
        }

        lines.push(...docs(undefined, member.obsolete).map(_ => `  ${_}`));
        lines.push(`  ${camelCase(member.name)}: ${this.#valueSpelling(display.value, display.nullable)};`);
      }

      lines.push("}");
      lines.push("");
    }

    return lines.join("\n");
  }

  #writeSources(): string {
    const lines = ["/** Every source a query may start from, by the name a client reads it under. */", "export interface Sources {"];
    const names = new Set<string>();
    for (const source of this.#description.sources) {
      const name = camelCase(source.name);
      if (names.has(name)) {
        throw new Error(`Two sources are read under '${name}'.`);
      }

      names.add(name);
      const stem = stemOf(this.#typeOf(source.model, `the source '${source.name}'`).model);
      lines.push(...docs(undefined, source.obsolete).map(_ => `  ${_}`));
      lines.push(`  readonly ${name}: scry.SourceTypes<${stem}Query, ${stem}Row>;`);
    }

    lines.push("}");
    lines.push("");
    return lines.join("\n");
  }

  #writeCommands(): string {
    const lines: string[] = [];
    const entries: string[] = [];
    for (const command of this.#description.commands) {
      const payload = `${command.name}Command`;
      this.#declare(payload, `the payload of the command '${command.name}'`);
      lines.push(...docs(`What the ${command.name} command is sent with.`, command.obsolete));
      lines.push(`export interface ${payload} {`);
      lines.push(...this.#plainMembers(command.name, command.properties, true));
      lines.push("}");
      lines.push("");

      let result = "void";
      if (command.result !== undefined) {
        result = command.result.name;
        this.#declare(result, `the result of the command '${command.name}'`);
        lines.push(`/** What the ${command.name} command completes with. */`);
        lines.push(`export interface ${result} {`);
        lines.push(...this.#plainMembers(command.result.name, command.result.properties, false));
        lines.push("}");
        lines.push("");
      }

      entries.push(...docs(undefined, command.obsolete).map(_ => `  ${_}`));
      entries.push(`  readonly ${camelCase(command.name)}: scry.CommandTypes<${payload}, ${result}>;`);
    }

    lines.push("/** Every command a client may send, by the name it is sent under. */");
    lines.push("export interface Commands {");
    lines.push(...entries);
    lines.push("}");
    lines.push("");
    return lines.join("\n");
  }

  // A payload or a result is a plain object: its lists are arrays, and it names no model. A payload's
  // nullable value may be left out, as a C# client leaves out one it never set.
  #plainMembers(owner: string, members: readonly ScryMemberInfo[], payload: boolean): string[] {
    const lines: string[] = [];
    for (const member of members) {
      const display = this.#parse(`${owner}.${member.name}`, member.typeDisplay);
      let optional = "";
      if (payload &&
          display.kind === "value" &&
          display.nullable) {
        optional = "?";
      }

      lines.push(...docs(undefined, member.obsolete).map(_ => `  ${_}`));
      lines.push(`  ${camelCase(member.name)}${optional}: ${this.#plainSpelling(`${owner}.${member.name}`, display)};`);
    }

    return lines;
  }

  #plainSpelling(where: string, display: Display): string {
    if (display.kind === "value") {
      return this.#valueSpelling(display.value, display.nullable);
    }

    if (display.kind === "list" &&
        display.element.kind === "value") {
      return `${parenthesized(this.#valueSpelling(display.element.value, display.element.nullable))}[]`;
    }

    throw new Error(`'${where}' is a '${display.kind}', which a command's payload or result cannot carry.`);
  }

  #writeSchema(): string {
    const schema: ScrySchema = {
      stamp: this.#description.schemaStamp,
      maxPageSize: this.#description.maxPageSize,
      queryUrlLimit: this.#description.queryUrlLimit,
      sources: Object.fromEntries(this.#description.sources.map(_ => [camelCase(_.name), this.#sourceInfo(_)])),
      models: Object.fromEntries(this.#description.types.map(_ => [_.model, this.#modelInfo(_)])),
      enums: Object.fromEntries([...this.#used].sort(ordinal).map(_ => [_, this.#enumNamed(_).info])),
      commands: Object.fromEntries(this.#description.commands.map(_ => [camelCase(_.name), this.#commandInfo(_)]))
    };

    return [
      "/**",
      " * What the types above cannot say at run time: the name each member travels under, what each",
      " * value is, and what a query that projects nothing projects.",
      " */",
      `export const schema = ${JSON.stringify(schema, null, 2)} as const satisfies scry.ScrySchema;`,
      ""
    ].join("\n");
  }

  #sourceInfo(source: ScrySourceInfo): SourceInfo {
    this.#typeOf(source.model, `the source '${source.name}'`);
    return {
      name: source.name,
      kind: source.kind,
      model: source.model,
      ...optional("obsolete", source.obsolete)
    };
  }

  #modelInfo(type: ScryTypeInfo): ModelInfo {
    const members: Record<string, MemberInfo> = {};
    for (const member of type.members) {
      members[camelCase(member.name)] = this.#memberInfo(type, member);
    }

    return {
      ...optional("base", type.base),
      ...flag("sensitive", type.isSensitive),
      ...optional("keys", type.keys),
      ...optional("obsolete", type.obsolete),
      defaultProjection: this.#scalars(type.model),
      members
    };
  }

  #memberInfo(type: ScryTypeInfo, member: ScryMemberInfo): MemberInfo {
    return {
      name: member.name,
      shape: this.#shape(member, this.#display(type, member)),
      ...flag("sensitive", member.isSensitive),
      ...optional("capability", member.command),
      ...optional("obsolete", member.obsolete)
    };
  }

  #commandInfo(command: ScryCommandInfo): CommandInfo {
    const payload: Record<string, MemberInfo> = {};
    for (const member of command.properties) {
      payload[camelCase(member.name)] = this.#plainInfo(command.name, member);
    }

    let result: CommandInfo["result"];
    if (command.result !== undefined) {
      const members: Record<string, MemberInfo> = {};
      for (const member of command.result.properties) {
        members[camelCase(member.name)] = this.#plainInfo(command.result.name, member);
      }

      result = { name: command.result.name, members };
    }

    return {
      name: command.name,
      ...optional("target", command.target),
      ...optional("keys", command.keys),
      payload,
      ...optional("result", result),
      ...optional("obsolete", command.obsolete)
    };
  }

  #plainInfo(owner: string, member: ScryMemberInfo): MemberInfo {
    const display = this.#parse(`${owner}.${member.name}`, member.typeDisplay);
    return {
      name: member.name,
      shape: this.#shape(member, display),
      ...optional("obsolete", member.obsolete)
    };
  }

  #shape(member: ScryMemberInfo, display: Display): ShapeInfo {
    if (display.kind === "value") {
      return { kind: "value", value: display.value, nullable: display.nullable };
    }

    if (display.kind === "model") {
      return { kind: "navigation", model: display.model };
    }

    if (display.kind === "attachment") {
      return { kind: "attachment", ...optional("contentType", member.contentType) };
    }

    if (display.element.kind === "model") {
      return { kind: "rows", model: display.element.model };
    }

    if (display.element.kind === "value") {
      return { kind: "values", value: display.element.value, nullable: display.element.nullable };
    }

    throw new Error(`'${member.name}' is a list of something a list cannot hold.`);
  }

  // What a query writing no projection projects: a base's scalars first, then this model's, in the
  // order it declares them. ModelSynthesizer.ScalarMembers, which the C# generator matches.
  #scalars(model: string): string[] {
    const type = this.#typeOf(model, `the model '${model}'`);
    const inherited = type.base === undefined ? [] : this.#scalars(type.base);
    return [...inherited, ...declaredOrder(type, type.members.filter(isScalar)).map(_ => _.name)];
  }

  #querySpelling(display: Display): string | undefined {
    if (display.kind === "value") {
      return `scry.Expr<${this.#valueSpelling(display.value, display.nullable)}>`;
    }

    if (display.kind === "model") {
      return `scry.Optional<${stemOf(display.model)}Query>`;
    }

    // No query reads an attachment: its bytes are fetched by the row's key.
    if (display.kind === "attachment") {
      return undefined;
    }

    if (display.element.kind === "model") {
      const stem = stemOf(display.element.model);
      return `scry.Collection<${stem}Query, ${stem}Row>`;
    }

    if (display.element.kind === "value") {
      return `scry.Collection<scry.Expr<${this.#valueSpelling(display.element.value, display.element.nullable)}>>`;
    }

    throw new Error("A list of something a list cannot hold.");
  }

  #valueSpelling(value: ValueInfo, nullable: boolean): string {
    let spelling: string;
    if ("scalar" in value) {
      spelling = scalarTypes[value.scalar];
    } else {
      const described = this.#enumNamed(value.enum);
      spelling = value.enum;
      if (described.info.flags) {
        spelling = `scry.Flags<${value.enum}>`;
      }
    }

    if (nullable) {
      return `${spelling} | null`;
    }

    return spelling;
  }

  // The display read and checked against what introspection says the member is, so the two
  // descriptions of one member can never be read as two different things.
  #display(type: ScryTypeInfo, member: ScryMemberInfo): Display {
    const where = `${type.model}.${member.name}`;
    const display = this.#parse(where, member.typeDisplay);
    const navigation = display.kind === "model";
    const collection = display.kind === "list";
    const attachment = display.kind === "attachment";
    if (navigation !== member.isNavigation ||
        collection !== member.isCollection ||
        attachment !== (member.isAttachment ?? false)) {
      throw new Error(`'${where}' is described as one kind of member, and its display, '${member.typeDisplay}', as another.`);
    }

    return display;
  }

  #parse(where: string, typeDisplay: string): Display {
    let display: Display;
    try {
      display = parseDisplay(typeDisplay, this.#known);
    } catch (error) {
      throw new Error(`'${where}': ${(error as Error).message}`, { cause: error });
    }

    this.#collectEnums(display);
    return display;
  }

  #collectEnums(display: Display): void {
    if (display.kind === "list") {
      this.#collectEnums(display.element);
      return;
    }

    if (display.kind === "value" &&
        "enum" in display.value) {
      this.#used.add(display.value.enum);
    }
  }

  #enumNamed(name: string): DescribedEnum {
    for (const described of this.#enums.values()) {
      if (described.name === name) {
        return described;
      }
    }

    throw new Error(`No enum is named '${name}'.`);
  }

  #typeOf(model: string, what: string): ScryTypeInfo {
    const type = this.#types.get(model);
    if (type === undefined) {
      throw new Error(`${what} names the model '${model}', which the description does not declare.`);
    }

    return type;
  }

  #extending(type: ScryTypeInfo): (kind: string) => string {
    if (type.base === undefined) {
      return () => "";
    }

    const stem = stemOf(this.#typeOf(type.base, `the model '${type.model}'`).model);
    return _ => ` extends ${stem}${_}`;
  }

  // A member is reached by its camel-cased name, through every model it is inherited by, so two that
  // case alike along one chain would be one member twice.
  #checkNames(type: ScryTypeInfo): void {
    const seen = new Map<string, string>();
    let current: ScryTypeInfo | undefined = type;
    while (current !== undefined) {
      for (const member of current.members) {
        const name = camelCase(member.name);
        const other = seen.get(name);
        if (other !== undefined) {
          throw new Error(`'${type.model}' reaches both '${other}' and '${current.model}.${member.name}' as '${name}'.`);
        }

        seen.set(name, `${current.model}.${member.name}`);
      }

      current = current.base === undefined ? undefined : this.#typeOf(current.base, `the model '${current.model}'`);
    }
  }

  #declare(identifier: string, what: string): void {
    const other = this.#identifiers.get(identifier);
    if (other !== undefined) {
      throw new Error(`Both ${other} and ${what} would be declared as '${identifier}'.`);
    }

    this.#identifiers.set(identifier, what);
  }
}

function enumInfo(described: Pick<ScryEnumInfo, "values" | "constants" | "isFlags" | "underlying">): EnumInfo {
  return {
    values: described.values,
    constants: described.constants ?? [],
    flags: described.isFlags ?? false,
    underlying: described.underlying
  };
}

function isScalar(member: ScryMemberInfo): boolean {
  return !member.isNavigation &&
         !member.isCollection &&
         !(member.isAttachment ?? false);
}

// Members in the order the model declares them, where the server says what that is; one the order does
// not name goes last, the rest kept as they were.
function declaredOrder(type: ScryTypeInfo, members: readonly ScryMemberInfo[]): ScryMemberInfo[] {
  const declared = type.declared;
  if (declared === undefined) {
    return [...members];
  }

  const position = (member: ScryMemberInfo) => {
    const index = declared.indexOf(member.name);
    if (index < 0) {
      return Number.MAX_SAFE_INTEGER;
    }

    return index;
  };
  return [...members].sort((left, right) => position(left) - position(right));
}

function stemOf(model: string): string {
  if (!model.endsWith(modelSuffix) ||
      model.length === modelSuffix.length) {
    throw new Error(`The model '${model}' is not named '{Type}${modelSuffix}', which every server model is.`);
  }

  return model.slice(0, -modelSuffix.length);
}

function parenthesized(spelling: string): string {
  if (spelling.includes(" ")) {
    return `(${spelling})`;
  }

  return spelling;
}

// A doc comment for what is described, deprecating it where the model does.
function docs(summary: string | undefined, obsolete: string | undefined): string[] {
  const lines: string[] = [];
  if (summary !== undefined) {
    lines.push(summary);
  }

  if (obsolete !== undefined) {
    lines.push(`@deprecated${obsolete.length === 0 ? "" : ` ${obsolete}`}`);
  }

  if (lines.length === 0) {
    return [];
  }

  const safe = lines.map(_ => _.replaceAll("*/", "*\\/").replaceAll(/\r?\n/g, " "));
  if (safe.length === 1) {
    return [`/** ${safe[0]} */`];
  }

  return ["/**", ...safe.map(_ => ` * ${_}`), " */"];
}

function optional<K extends string, V>(key: K, value: V | undefined): { [P in K]?: V } {
  if (value === undefined) {
    return {};
  }

  return { [key]: value } as { [P in K]: V };
}

function flag<K extends string>(key: K, value: boolean | undefined): { [P in K]?: true } {
  if (value !== true) {
    return {};
  }

  return { [key]: true } as { [P in K]: true };
}

function ordinal(left: string, right: string): number {
  if (left < right) {
    return -1;
  }

  if (left > right) {
    return 1;
  }

  return 0;
}
